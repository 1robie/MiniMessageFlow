package fr.robie.minimessageflow;

import net.kyori.adventure.pointer.Pointered;
import net.kyori.adventure.text.Component;
import net.kyori.adventure.text.ComponentLike;
import net.kyori.adventure.text.serializer.legacy.LegacyComponentSerializer;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.function.Function;
import java.util.function.Supplier;

/**
 * Sealed interface representing different types of placeholder values.
 *
 * <p>A value is text or a component, and is fixed, computed at each render, or computed for the viewer:
 * <table>
 *   <caption>Kinds of values</caption>
 *   <tr><td></td><td>text</td><td>component</td></tr>
 *   <tr><td>fixed</td><td>{@link StaticValue}</td><td>{@link ComponentValue}</td></tr>
 *   <tr><td>at each render</td><td>{@link DynamicValue}</td><td>{@link DynamicComponentValue}</td></tr>
 *   <tr><td>for the viewer</td><td>{@link ViewerValue}</td><td>{@link ViewerComponentValue}</td></tr>
 * </table>
 * Text is never read as MiniMessage or legacy codes; a component is inserted with its own style. Where only text can
 * go (a tag argument such as a click's command, a modifier such as {@code %name.upper%}), a component gives its plain
 * text.
 *
 * <p>Usage is typically internal; use {@link Placeholder} to create placeholder values.
 */
public sealed interface PlaceholderValue permits PlaceholderValue.StaticValue, PlaceholderValue.DynamicValue,
        PlaceholderValue.ViewerValue, PlaceholderValue.ComponentValue, PlaceholderValue.DynamicComponentValue,
        PlaceholderValue.ViewerComponentValue {

    /**
     * Evaluates this placeholder value as text. A component value gives its legacy ({@code §}) text, for
     * {@code Placeholder#parse}.
     *
     * @param viewer the viewer (read through its pointers), may be null for values that do not depend on it
     * @return the evaluated string value, never null
     * @throws Exception if evaluation fails
     */
    @NotNull String evaluate(@Nullable Pointered viewer) throws Exception;

    /**
     * Evaluates this placeholder value as a component: the component of a component value, the text of a text value
     * as plain text.
     *
     * @param viewer the viewer, may be null for values that do not depend on it
     * @return the component, never null
     * @throws Exception if evaluation fails
     */
    default @NotNull Component asComponent(@Nullable Pointered viewer) throws Exception {
        return Component.text(this.evaluate(viewer));
    }

    /**
     * Whether this value is a component (inserted with its own style) rather than text.
     */
    default boolean isComponent() {
        return false;
    }

    /**
     * Whether this value depends on the viewer.
     */
    default boolean needsViewer() {
        return false;
    }

    /**
     * A static placeholder value with a fixed string.
     *
     * @param value the static string value (never null)
     */
    record StaticValue(@NotNull String value) implements PlaceholderValue {

        public StaticValue(@NotNull String value) {
            this.value = value != null ? value : "";
        }

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) {
            return this.value;
        }
    }

    /**
     * A dynamic placeholder value generated by a supplier.
     * No viewer required; evaluated the same way for every viewer.
     *
     * @param supplier the supplier that generates the string value
     */
    record DynamicValue(@NotNull Supplier<String> supplier) implements PlaceholderValue {

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) throws Exception {
            String result = this.supplier.get();
            return result != null ? result : "";
        }
    }

    /**
     * A viewer-specific placeholder value generated by a function.
     * The value depends on the viewer.
     *
     * @param function the function that generates the string value from the viewer
     */
    record ViewerValue(@NotNull Function<Pointered, String> function) implements PlaceholderValue {

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) throws Exception {
            if (viewer == null) {
                return "";
            }
            String result = this.function.apply(viewer);
            return result != null ? result : "";
        }

        @Override
        public boolean needsViewer() {
            return true;
        }
    }

    /**
     * A ready-made component, inserted as is.
     */
    record ComponentValue(@NotNull Component component) implements PlaceholderValue {

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) {
            return legacyText(this.component);
        }

        @Override
        public @NotNull Component asComponent(@Nullable Pointered viewer) {
            return this.component;
        }

        @Override
        public boolean isComponent() {
            return true;
        }
    }

    /**
     * A component generated by a supplier at each render (an item's display name, a clickable name...). A null
     * result is an empty component.
     *
     * @param supplier the supplier that generates the component
     */
    record DynamicComponentValue(@NotNull Supplier<? extends ComponentLike> supplier) implements PlaceholderValue {

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) {
            return legacyText(this.asComponent(viewer));
        }

        @Override
        public @NotNull Component asComponent(@Nullable Pointered viewer) {
            ComponentLike result = this.supplier.get();
            return result != null ? result.asComponent() : Component.empty();
        }

        @Override
        public boolean isComponent() {
            return true;
        }
    }

    /**
     * A component generated for the viewer by a function. Without a viewer, or for a null result, an empty component.
     *
     * @param function the function that generates the component from the viewer
     */
    record ViewerComponentValue(@NotNull Function<Pointered, ? extends ComponentLike> function) implements PlaceholderValue {

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) {
            return legacyText(this.asComponent(viewer));
        }

        @Override
        public @NotNull Component asComponent(@Nullable Pointered viewer) {
            if (viewer == null) {
                return Component.empty();
            }
            ComponentLike result = this.function.apply(viewer);
            return result != null ? result.asComponent() : Component.empty();
        }

        @Override
        public boolean isComponent() {
            return true;
        }

        @Override
        public boolean needsViewer() {
            return true;
        }
    }

    private static @NotNull String legacyText(@NotNull Component component) {
        return LegacyComponentSerializer.legacySection().serialize(component);
    }

    static @NotNull PlaceholderValue ofComponent(@NotNull Component component) {
        return new ComponentValue(component);
    }

    /**
     * Creates a component value generated at each render.
     *
     * @param supplier the supplier
     * @return a new DynamicComponentValue
     */
    static @NotNull PlaceholderValue ofDynamicComponent(@NotNull Supplier<? extends ComponentLike> supplier) {
        return new DynamicComponentValue(supplier);
    }

    /**
     * Creates a component value generated for the viewer.
     *
     * @param function the viewer function
     * @return a new ViewerComponentValue
     */
    static @NotNull PlaceholderValue ofViewerComponent(@NotNull Function<Pointered, ? extends ComponentLike> function) {
        return new ViewerComponentValue(function);
    }

    /**
     * Creates a static placeholder value.
     *
     * @param value the static string value
     * @return a new StaticValue
     */
    static @NotNull PlaceholderValue ofStatic(@NotNull String value) {
        return new StaticValue(value);
    }

    /**
     * Creates a dynamic placeholder value.
     *
     * @param supplier the supplier function
     * @return a new DynamicValue
     */
    static @NotNull PlaceholderValue ofDynamic(@NotNull Supplier<String> supplier) {
        return new DynamicValue(supplier);
    }

    /**
     * Creates a viewer-specific placeholder value.
     *
     * @param function the viewer function
     * @return a new ViewerValue
     */
    static @NotNull PlaceholderValue ofViewer(@NotNull Function<Pointered, String> function) {
        return new ViewerValue(function);
    }
}
