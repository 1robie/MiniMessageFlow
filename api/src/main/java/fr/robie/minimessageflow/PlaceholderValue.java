package fr.robie.minimessageflow;

import net.kyori.adventure.text.Component;
import net.kyori.adventure.text.serializer.legacy.LegacyComponentSerializer;
import net.kyori.adventure.pointer.Pointered;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.function.Function;
import java.util.function.Supplier;

/**
 * Sealed interface representing different types of placeholder values.
 *
 * <p>Placeholders can be:
 * <ul>
 *   <li>{@link StaticValue} - Fixed string value</li>
 *   <li>{@link DynamicValue} - Supplier that generates a value at resolution time</li>
 *   <li>{@link ViewerValue} - Function that generates a value based on the viewer</li>
 * </ul>
 *
 * <p>Usage is typically internal; use {@link fr.robie.messageflow.formatter.Placeholder}
 * or {@link GlobalPlaceholderRegistry} to create and manage placeholder values.
 */
public sealed interface PlaceholderValue permits PlaceholderValue.StaticValue, PlaceholderValue.DynamicValue, PlaceholderValue.ViewerValue, PlaceholderValue.ComponentValue {

    /**
     * Evaluates this placeholder value.
     *
     * @param viewer the viewer (read through its pointers), may be null for values that do not depend on it
     * @return the evaluated string value, never null
     * @throws Exception if evaluation fails
     */
    @NotNull String evaluate(@Nullable Pointered viewer) throws Exception;

    /**
     * A static placeholder value with a fixed string.
     *
     * @param value the static string value (never null)
     */
    record StaticValue(@NotNull String value) implements PlaceholderValue {

        public StaticValue(@NotNull String value) {
            this.value = value != null ? value : "";
        }

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) {
            return this.value;
        }
    }

    /**
     * A dynamic placeholder value generated by a supplier.
     * No viewer required; evaluated the same way for every viewer.
     *
     * @param supplier the supplier that generates the string value
     */
    record DynamicValue(@NotNull Supplier<String> supplier) implements PlaceholderValue {

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) throws Exception {
            String result = this.supplier.get();
            return result != null ? result : "";
        }
    }

    /**
     * A viewer-specific placeholder value generated by a function.
     * The value depends on the viewer.
     *
     * @param function the function that generates the string value from the viewer
     */
    record ViewerValue(@NotNull Function<Pointered, String> function) implements PlaceholderValue {

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) throws Exception {
            if (viewer == null) {
                return "";
            }
            String result = this.function.apply(viewer);
            return result != null ? result : "";
        }
    }

    /**
     * A ready-made component, inserted as is (Adventure only). On the legacy platform, and in
     * {@code Placeholder#parse}, it is its legacy ({@code §}) text.
     */
    record ComponentValue(@NotNull Component component) implements PlaceholderValue {

        @Override
        public @NotNull String evaluate(@Nullable Pointered viewer) {
            return LegacyComponentSerializer.legacySection().serialize(this.component);
        }
    }

    static @NotNull PlaceholderValue ofComponent(@NotNull Component component) {
        return new ComponentValue(component);
    }

    /**
     * Creates a static placeholder value.
     *
     * @param value the static string value
     * @return a new StaticValue
     */
    static @NotNull PlaceholderValue ofStatic(@NotNull String value) {
        return new StaticValue(value);
    }

    /**
     * Creates a dynamic placeholder value.
     *
     * @param supplier the supplier function
     * @return a new DynamicValue
     */
    static @NotNull PlaceholderValue ofDynamic(@NotNull Supplier<String> supplier) {
        return new DynamicValue(supplier);
    }

    /**
     * Creates a viewer-specific placeholder value.
     *
     * @param function the viewer function
     * @return a new ViewerValue
     */
    static @NotNull PlaceholderValue ofViewer(@NotNull Function<Pointered, String> function) {
        return new ViewerValue(function);
    }
}
